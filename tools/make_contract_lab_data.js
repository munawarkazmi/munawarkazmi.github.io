#!/usr/bin/env node
/* Regenerates assets/contract-lab-data.js from toolcall-contract checked out
 * beside this site: the tool catalog with its schemas and contract rules,
 * the catalogs the rules refer to, both models' committed responses (task
 * and raw text, without the prompt), and the constructed tier.
 *
 *   node tools/make_contract_lab_data.js
 */
'use strict';
const fs = require('fs'), path = require('path');
const REPO = path.join(__dirname, '..', '..', 'toolcall-contract');
if (!fs.existsSync(REPO)) { console.error('toolcall-contract not found beside the site'); process.exit(2); }
const J = (f) => JSON.parse(fs.readFileSync(path.join(REPO, f), 'utf8'));
const L = (f) => fs.readFileSync(path.join(REPO, f), 'utf8').trim().split('\n').map((l) => JSON.parse(l));
const data = {
  tools: J('tools_catalog/tools.json'), catalogs: J('tools_catalog/catalogs.json'),
  models: {
    qwen: { name: 'qwen2.5:7b-instruct', records: L('datasets/qwen2.5-7b-instruct.jsonl').map((r) => ({ id: r.id, task: r.task, raw: r.raw })) },
    llama: { name: 'llama-3.3-70b-versatile', records: L('datasets/llama-3.3-70b-versatile.jsonl').map((r) => ({ id: r.id, task: r.task, raw: r.raw })) },
  },
  constructed: L('datasets/constructed.jsonl').map((r) => ('call' in r ? { id: r.id, cls: r.class, expected: r.expected, call: r.call } : { id: r.id, cls: r.class, expected: r.expected, raw: r.raw })),
};
const header = '/* toolcall-contract, as committed there: tools_catalog/tools.json and\n   catalogs.json, both models\' responses from datasets/*.jsonl (task and raw\n   text only), and datasets/constructed.jsonl.\n   Generated by tools/make_contract_lab_data.js; do not edit by hand. */\n';
fs.writeFileSync(path.join(__dirname, '..', 'assets', 'contract-lab-data.js'), header + 'window.CONTRACT_LAB_DATA = ' + JSON.stringify(data) + ';\n');
console.log('wrote assets/contract-lab-data.js: ' + data.tools.length + ' tools, ' + data.models.qwen.records.length + ' + ' + data.models.llama.records.length + ' model responses, ' + data.constructed.length + ' constructed cases');
