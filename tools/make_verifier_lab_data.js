#!/usr/bin/env node
/* Regenerates assets/verifier-lab-data.js from the ros2-llm-safety-verifier
 * repository checked out beside this site, the way tools/drift.py expects.
 *
 *   node tools/make_verifier_lab_data.js
 *
 * Six scenarios are chosen so that between them the two models' committed
 * proposals cover every verdict the verifier can give: safe, off_map,
 * discontinuity, collision and unknown_region. The maps are the
 * repository's own 240 by 180 PGM grids, run-length encoded.
 */
'use strict';
const fs = require('fs'), path = require('path');
const REPO = path.join(__dirname, '..', '..', 'ros2-llm-safety-verifier');
const PICK = [0, 4, 8, 12, 20, 21];
const MODELS = { 'qwen2.5-7b-instruct': 'qwen', 'llama-3.3-70b-versatile': 'llama' };

function pgm(file) {
  const b = fs.readFileSync(file); let i = 0; const tok = [];
  while (tok.length < 4) { while (b[i] === 0x0a || b[i] === 0x20) i++; let j = i; while (b[j] !== 0x0a && b[j] !== 0x20) j++; tok.push(b.slice(i, j).toString()); i = j; }
  i++;
  return { w: +tok[1], h: +tok[2], data: new Uint8Array(b.buffer, b.byteOffset + i) };
}
function rle(d) {
  const out = []; let v = d[0], n = 0;
  const kind = (c) => (c === 0 ? 0 : c === 254 ? 1 : 2);
  for (const c of d) { if (c === v) n++; else { out.push(kind(v), n); v = c; n = 1; } }
  out.push(kind(v), n); return out;
}
function scenarioFile(sc, ext) { return path.join(REPO, 'llm_eval', 'scenarios', `scenario_${String(sc).padStart(2, '0')}.${ext}`); }

if (!fs.existsSync(REPO)) { console.error('ros2-llm-safety-verifier not found beside the site'); process.exit(2); }
const parsed = {}, csv = {};
for (const m in MODELS) {
  parsed[m] = JSON.parse(fs.readFileSync(path.join(REPO, 'llm_eval', 'parsed', m + '.json')));
  csv[m] = fs.readFileSync(path.join(REPO, 'reports', 'results', 'llm_eval_' + m + '.csv'), 'utf8').trim().split('\n').slice(1).map((l) => l.split(','));
}
const out = [];
for (const sc of PICK) {
  const s = JSON.parse(fs.readFileSync(scenarioFile(sc, 'json')));
  const p = pgm(scenarioFile(sc, 'pgm'));
  if (p.w !== s.width || p.h !== s.height) throw new Error('grid size mismatch on scenario ' + sc);
  const e = { id: sc, width: s.width, height: s.height, resolution: s.resolution, start: s.start, goal: s.goal, cells: rle(p.data), proposals: {} };
  for (const m in MODELS) {
    const pr = parsed[m].find((r) => r.scenario === sc), row = csv[m].find((r) => +r[0] === sc);
    e.proposals[MODELS[m]] = {
      waypoints: pr.waypoints.map((w) => [+w[0].toFixed(4), +w[1].toFixed(4)]),
      recorded: { safe: row[4] === '1', violation: row[5], index: +row[6], bucket: row[1], endpoints_ok: row[2] === '1' },
    };
  }
  out.push(e);
}
const header = '/* Six of the forty evaluation scenarios from ros2-llm-safety-verifier, with\n   both models\' committed proposals and the verdicts the C++ verifier\n   recorded for them (reports/results/llm_eval_*.csv). Maps are the\n   repository\'s own 240 by 180 occupancy grids at 0.05 m, run-length\n   encoded as [kind, count, ...] with kind 0 free, 1 lethal, 2 unknown.\n   Generated by tools/make_verifier_lab_data.js; do not edit by hand. */\n';
fs.writeFileSync(path.join(__dirname, '..', 'assets', 'verifier-lab-data.js'), header + 'window.VERIFIER_LAB_DATA = ' + JSON.stringify(out) + ';\n');
console.log('wrote assets/verifier-lab-data.js with ' + out.length + ' scenarios');
