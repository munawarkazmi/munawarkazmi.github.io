#!/usr/bin/env node
/* Regenerates assets/bounds-lab-data.js from legibility-bounds checked out
 * beside this site: every row of results/suite_bounds.json, with the run's
 * provenance fields.
 *
 *   node tools/make_bounds_lab_data.js
 */
'use strict';
const fs = require('fs'), path = require('path');
const REPO = path.join(__dirname, '..', '..', 'legibility-bounds');
const src = path.join(REPO, 'results', 'suite_bounds.json');
if (!fs.existsSync(src)) { console.error('legibility-bounds/results/suite_bounds.json not found beside the site'); process.exit(2); }
const d = JSON.parse(fs.readFileSync(src, 'utf8'));
const out = { geometry_commit: d.geometry_commit, observer: d.observer, grid: d.grid, violations: d.violations,
  rows: d.rows.map((r) => ({ scenario: r.scenario, ceiling: r.ceiling, achieved: r.achieved, bound: r.bound, gap: r.gap, shortest: r.shortest_path_legibility, achieved_source: r.achieved_source,
    detour_certified: r.detour_certified, has_obstacles: r.has_obstacles, band_cells: r.band_cells, uncertified_cells: r.uncertified_cells, lattice_seconds: r.lattice_build_seconds })) };
const header = '/* legibility-bounds, as committed there: every row of results/suite_bounds.json.\n   Generated by tools/make_bounds_lab_data.js; do not edit by hand. */\n';
fs.writeFileSync(path.join(__dirname, '..', 'assets', 'bounds-lab-data.js'), header + 'window.BOUNDS_LAB_DATA = ' + JSON.stringify(out) + ';\n');
console.log('wrote assets/bounds-lab-data.js: ' + out.rows.length + ' rows');
