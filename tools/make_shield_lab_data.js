#!/usr/bin/env node
/* Regenerates assets/shield-lab-data.js from llm-nav-shield checked out
 * beside this site: for each map the verifier demo ships, the bucket and
 * action the C++ shield recorded for qwen's proposal, and for the first
 * ten scenarios the sealed-goal result too.
 *
 *   node tools/make_shield_lab_data.js
 */
'use strict';
const fs = require('fs'), path = require('path');
const REPO = path.join(__dirname, '..', '..', 'llm-nav-shield');
if (!fs.existsSync(REPO)) { console.error('llm-nav-shield not found beside the site'); process.exit(2); }
global.window = {}; require(path.join(__dirname, '..', 'assets', 'verifier-lab-data.js'));
const csv = fs.readFileSync(path.join(REPO, 'reports', 'results', 'shield_eval.csv'), 'utf8').trim().split('\n').slice(1).map((l) => l.split(','));
const out = {};
for (const e of global.window.VERIFIER_LAB_DATA) {
  const q = csv.find((r) => +r[0] === e.id && r[1] === 'qwen'), s = csv.find((r) => +r[0] === e.id && r[1] === 'sealed_goal');
  out[e.id] = { bucket: q[2], action: q[3], fallback_waypoints: +q[5], sealed: s ? { bucket: s[2], action: s[3] } : null };
}
const header = '/* What the C++ shield recorded (reports/results/shield_eval.csv in\n   llm-nav-shield) for qwen\'s proposal on each map the verifier demo ships,\n   and for the sealed-goal variant where the halt suite covers it.\n   Generated by tools/make_shield_lab_data.js; do not edit by hand. */\n';
fs.writeFileSync(path.join(__dirname, '..', 'assets', 'shield-lab-data.js'), header + 'window.SHIELD_LAB_DATA = ' + JSON.stringify(out) + ';\n');
console.log('wrote assets/shield-lab-data.js for maps ' + Object.keys(out).join(', '));
