#!/usr/bin/env node
/* Regenerates assets/planner-lab-data.js from plan-failure-bench checked out
 * beside this site: both environments, their seeds, and the plain-condition
 * response of each of the four models to every seed, with the verdict the
 * checker recorded.
 *
 *   node tools/make_planner_lab_data.js
 */
'use strict';
const fs = require('fs'), path = require('path');
const REPO = path.join(__dirname, '..', '..', 'plan-failure-bench');
if (!fs.existsSync(REPO)) { console.error('plan-failure-bench not found beside the site'); process.exit(2); }
const J = (f) => JSON.parse(fs.readFileSync(path.join(REPO, f), 'utf8'));
const L = (f) => fs.readFileSync(path.join(REPO, f), 'utf8').trim().split('\n').filter(Boolean).map((l) => JSON.parse(l));
const MODELS = { gemini_flash: 'Gemini 3.6 Flash', gemini_flash_lite: 'Gemini 3.1 Flash Lite', groq_llama70b: 'Llama 3.3 70B', local_qwen: 'Qwen 2.5 7B' };
const FILES = { house_01: { gemini_flash: 'gemini_flash_plain', gemini_flash_lite: 'gemini_flash_lite_plain', groq_llama70b: 'groq_llama70b_plain', local_qwen: 'local_qwen_plain' },
  office_01: { gemini_flash: 'gemini_flash_office_plain', gemini_flash_lite: 'gemini_flash_lite_office_plain', groq_llama70b: 'groq_llama70b_office_plain', local_qwen: 'local_qwen_office_plain' } };
const out = { models: MODELS, environments: {} };
for (const envName of ['house_01', 'office_01']) {
  const env = J('environments/' + envName + '.json');
  const seeds = J('instructions/seeds_' + envName + '.json').map((s) => ({ id: s.id, label: s.label, instruction: s.instruction, goal: s.goal, alternatives: s.alternatives || null,
    expected_terminal: s.expected_terminal, reference_plan: s.reference_plan || null, notes: s.notes || '' }));
  const responses = {};
  for (const m in FILES[envName]) responses[m] = L('results/' + FILES[envName][m] + '.jsonl').map((r) => ({ seed: r.seed_id, response: r.response, verdict: r.verdict, detail: r.detail, step_index: r.step_index, goal_satisfied: r.goal_satisfied, goal_total: r.goal_total, invariant_breached: r.invariant_breached, per_alternative: r.per_alternative }));
  out.environments[envName] = { env: env, seeds: seeds, responses: responses };
}
const header = '/* plan-failure-bench, as committed there: environments/*.json, the seeds in\n   instructions/seeds_*.json, and each model\'s plain-condition response to\n   every seed from results/*_plain.jsonl with the verdict the checker recorded.\n   Generated by tools/make_planner_lab_data.js; do not edit by hand. */\n';
fs.writeFileSync(path.join(__dirname, '..', 'assets', 'planner-lab-data.js'), header + 'window.PLANNER_LAB_DATA = ' + JSON.stringify(out) + ';\n');
console.log('wrote assets/planner-lab-data.js: 2 environments, ' + out.environments.house_01.seeds.length + ' + ' + out.environments.office_01.seeds.length + ' seeds, 8 response sets');
