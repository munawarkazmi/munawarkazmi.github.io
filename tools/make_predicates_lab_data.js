#!/usr/bin/env node
/* Regenerates assets/predicates-lab-data.js from the exact-predicates
 * repository checked out beside this site: the two adversarial corpora,
 * line for line, as strings (the coordinates exceed what a JavaScript
 * number can hold, so the page parses them as BigInt).
 *
 *   node tools/make_predicates_lab_data.js
 */
'use strict';
const fs = require('fs'), path = require('path');
const REPO = path.join(__dirname, '..', '..', 'exact-predicates');
if (!fs.existsSync(REPO)) { console.error('exact-predicates not found beside the site'); process.exit(2); }
const read = (f) => fs.readFileSync(path.join(REPO, 'corpus', f), 'utf8').trim().split('\n').map((l) => l.trim().split(/\s+/).join(' '));
const data = { orientation: read('orientation_adversarial.txt'), incircle: read('incircle_adversarial.txt') };
const header = '/* The adversarial corpus of exact-predicates, as committed there:\n   corpus/orientation_adversarial.txt (ax ay bx by cx cy expected) and\n   corpus/incircle_adversarial.txt (a b c d as x y pairs, then expected).\n   Generated by tools/make_predicates_lab_data.js; do not edit by hand. */\n';
fs.writeFileSync(path.join(__dirname, '..', 'assets', 'predicates-lab-data.js'), header + 'window.PREDICATES_LAB_DATA = ' + JSON.stringify(data) + ';\n');
console.log('wrote assets/predicates-lab-data.js: ' + data.orientation.length + ' orientation and ' + data.incircle.length + ' in-circle cases');
